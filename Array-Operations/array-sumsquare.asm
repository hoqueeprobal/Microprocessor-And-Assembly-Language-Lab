.MODEL SMALL
.STACK 100H

.DATA
A DB "1","0","2","1"
B DB "2","2","1","1"
D DB 4 DUP(?)

.CODE
MAIN PROC
    MOV AX,@DATA
    MOV DS,AX

    MOV SI,0
    MOV CX,4

CALCULATION:
    MOV AL,A[SI]
    SUB AL,30H
    MOV BL,B[SI]
    SUB BL,30H

    ADD AL,BL
    MOV AH,0
    MUL AL

    ADD AL,30H
    MOV D[SI],AL

    INC SI
    LOOP CALCULATION

    MOV SI,0
    MOV CX,4

PRINT:
    MOV DL,D[SI]
    MOV AH,2
    INT 21H
    INC SI
    LOOP PRINT

    MOV AH,4CH
    INT 21H

MAIN ENDP
END MAIN
